// Deterministic country pick per round so both peers see the same prompt
// without an extra round-trip. Seed = roomCode + roundIndex.
export function pickCountry(roomCode, roundIndex) {
  const seedStr = `${roomCode}::${roundIndex}`;
  let h = 0;
  for (let i = 0; i < seedStr.length; i++) h = (Math.imul(31, h) + seedStr.charCodeAt(i)) | 0;
  const idx = Math.abs(h) % COUNTRIES.length;
  return { ...COUNTRIES[idx], index: idx };
}
